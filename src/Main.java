public class Main {
    public static void main(String[] args) {

        int numToExamine = 5;
        int remainder = numToExamine % 2;

        System.out.println("The number is: " + numToExamine);
        System.out.println("The remainder when divided by 2 is: " + remainder);
        System.out.println("A remainder of 0 means the number is even.");
        System.out.println("A remainder of 1 means the number is odd.");
    }
}